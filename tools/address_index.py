"""Lists every game address and offset the co-op code names, with what it is for, as one Markdown index.

The addresses (main+ offsets into the game's code and data, guest pointers, struct and actor field offsets) live
next to the code that uses them, with their meaning in a comment beside or above the constant. This gathers them:
each constant whose value is a hex literal, its file and line, and its comment (the same line's, else the comment
lines right above it). Run it again after a game update or a scan; the code stays the source.

    python -I tools/address_index.py [--out docs/addresses.md]

Standard library only. Only our own code is read; nothing from the game.
"""
import argparse
import os
import re
import sys

ROOTS = ("lichii/hook", "hookshot/src", "coop/host")
EXTS = (".h", ".hpp", ".cpp", ".inc")
CONST = re.compile(r"^\s*(?:inline\s+)?(?:static\s+)?constexpr\s+[\w:<>]+(?:\s*\*)?\s+(k?\w+)\s*(?:\{|=)\s*(0x[0-9a-fA-F']+)")
COMMENT = re.compile(r"//\s?(.*)$")


def comment_for(lines, i):
    """The constant's own trailing comment, else the comment block right above it (up to 6 lines)."""
    m = COMMENT.search(lines[i])
    if m and "0x" in lines[i][:m.start()]:
        text = m.group(1).strip()
        if text:
            return text
    above = []
    j = i - 1
    skipped = 0
    while j >= 0 and len(above) < 6:
        s = lines[j].strip()
        if s.startswith("//"):
            above.insert(0, s.lstrip("/").strip())
            j -= 1
            continue
        # A constant in a group under one comment block: go up past its neighbours to the group's comment.
        if not above and skipped < 20 and (CONST.match(lines[j]) or (s and s.startswith("constexpr"))):
            skipped += 1
            j -= 1
            continue
        break
    text = " ".join(above)
    return ("(group) " + text) if text and skipped else text


def scan(repo):
    out = {}
    for root in ROOTS:
        for d, _, files in os.walk(os.path.join(repo, root)):
            for f in sorted(files):
                if not f.endswith(EXTS):
                    continue
                path = os.path.join(d, f)
                rel = os.path.relpath(path, repo).replace(os.sep, "/")
                with open(path, encoding="utf-8", errors="replace") as fh:
                    lines = fh.read().splitlines()
                for i, line in enumerate(lines):
                    m = CONST.match(line)
                    if not m:
                        continue
                    name, value = m.group(1), m.group(2).replace("'", "")
                    if int(value, 16) < 0x10 and not name.lower().startswith(("k", "off")):
                        continue
                    text = comment_for(lines, i).replace("|", "\\|")
                    out.setdefault(rel, []).append((i + 1, name, value, text))
    return out


def render(index):
    total = sum(len(v) for v in index.values())
    parts = ["# Game addresses and offsets in the co-op code",
             "",
             "Generated by `tools/address_index.py` from the code (%d constants in %d files). Each row: the constant, "
             "its value, where it is, and the comment the code gives it. Values named `main+` or used with the module "
             "base are offsets into the game's main module; others are field offsets into a game object (actor, "
             "component, node) or plain IDs and hashes. The code is the source: read the line for the context. Only "
             "single `constexpr` constants are listed: arrays of values, `#define`s and addresses written inline in "
             "the code are not (search the code for those). Regenerate after a code change: the line numbers move." % (
                 total, len(index)), ""]
    for rel in sorted(index):
        parts.append("## `%s`" % rel)
        parts.append("")
        parts.append("| Constant | Value | Line | What it is |")
        parts.append("| --- | --- | --- | --- |")
        for line, name, value, text in index[rel]:
            parts.append("| `%s` | `%s` | [%d](../%s#L%d) | %s |" % (name, value, line, rel, line, text or ""))
        parts.append("")
    return "\n".join(parts)


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--repo", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
    p.add_argument("--out", help="write here (default: print)")
    a = p.parse_args(argv)
    text = render(scan(os.path.abspath(a.repo)))
    if a.out:
        with open(a.out, "w", encoding="utf-8", newline="\n") as f:
            f.write(text + "\n")
    else:
        sys.stdout.write(text + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
