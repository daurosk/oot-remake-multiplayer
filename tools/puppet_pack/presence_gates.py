"""Writes lichii/hook/coop_presence_gates.inc: the placements a shared flag gates in the dungeons (row 233).

    python -m puppet_pack.presence_gates --romfs <extracted romfs> --out lichii/hook/coop_presence_gates.inc

Row 233 (Geno's survey): some placements exist only while a flag holds (`Presence.FlagName`, `IsNegation` in
Banc/<area>/*.bcett.byml): the Water Temple's water planes and waterfalls (WaterTemple_WaterLevelChange01/03), the
Shadow Temple's tower pillar, Bottom of the Well's water, and more. When such a flag is a shared one, another
game's play can change it while our Link is in that dungeon. Whether the game takes the gated pieces away or puts
them in then, or only at the next load, is to be seen in a game: the hook's probe (coop_presence_gates.h) logs,
for every row's flag that changes, which of its pieces are in our game a few seconds later.

Kept: a placement in a dungeon area whose presence flag is shared (named in lichii/hook/coop_dungeon.cpp or
coop_story.cpp), and whose actor is a piece of the room (Obj_, Land_, FldObj_, Dm_ names). Enemies are left out
(an enemy's delete or appearance is proven live), and so are effects, sounds and areas.
Only flag names, their Murmur3 hashes, area and actor names go in the file.
"""
import argparse
import collections
import glob
import os
import re
import sys

if __package__ in (None, ""):
    sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    __package__ = "puppet_pack"  # noqa: A001

from . import byml, zs  # noqa: E402
from .boss_beaten import murmur3  # noqa: E402

DUNGEONS = (
    "BottomOfTheWell", "DodongoCavern", "FireTemple", "ForestTemple", "GanonCastle", "GerudoTrainingGround",
    "IceCavern", "InsideGanonCastle", "InsideJabuJabuBelly", "InsideTheDekuTree", "ShadowTemple", "SpiritTemple",
    "WaterTemple",
)
PIECES = ("Obj_", "Land_", "FldObj_", "Dm_")
SHARED_FILES = ("lichii/hook/coop_dungeon.cpp", "lichii/hook/coop_story.cpp")
ENTRY = re.compile(r'\{\s*0x([0-9a-fA-F]{8})\s*,\s*(?:true|false|[A-Za-z_:]+)\s*,\s*"([^"]+)"')


def shared_flags(repo):
    names = set()
    for rel in SHARED_FILES:
        with open(os.path.join(repo, rel), encoding="utf-8") as f:
            for value, name in ENTRY.findall(f.read()):
                if murmur3(name) == int(value, 16):
                    names.add(name)
    return names


def is_piece(gyaml):
    return isinstance(gyaml, str) and gyaml.startswith(PIECES)


def gates(placements, shared):
    """(flag, negation, area, actor) -> count, from (area, actor, presence) triples."""
    rows = collections.Counter()
    for area, gyaml, presence in placements:
        if not isinstance(presence, dict):
            continue
        flag = presence.get("FlagName")
        if not flag or flag not in shared or not is_piece(gyaml):
            continue
        rows[(flag, bool(presence.get("IsNegation", False)), area, gyaml)] += 1
    return rows


def read_placements(romfs):
    dicts = zs.Dicts.from_romfs(romfs)
    for area in DUNGEONS:
        for path in sorted(glob.glob(os.path.join(romfs, "Banc", area, "**", "*.bcett.byml*"), recursive=True)):
            with open(path, "rb") as f:
                raw = zs.maybe_decompress(dicts, f.read())
            try:
                doc = byml.loads(raw)
            except Exception:  # noqa: BLE001 - a file this reader does not know is not a map
                continue
            for actor in (doc.get("Actors") or []) if isinstance(doc, dict) else []:
                if isinstance(actor, dict):
                    yield area, actor.get("Gyaml"), actor.get("Presence")


def render(rows):
    out = [
        "// Generated by tools/puppet_pack/presence_gates.py from the game's romfs; do not edit.",
        "// Row 233: dungeon placements (room pieces) that exist only while a shared flag holds (negation: while it",
        "// does not). {flag hash, negation, area, actor, placements, flag}",
    ]
    for (flag, negation, area, gyaml), count in sorted(rows.items(), key=lambda r: (r[0][2], r[0][0], r[0][3], r[0][1])):
        out.append(f'    {{0x{murmur3(flag):08x}, {"true" if negation else "false"}, "{area}", "{gyaml}", {count}, "{flag}"}},')
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--romfs", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--repo", default=os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
    args = ap.parse_args(argv)
    rows = gates(read_placements(args.romfs), shared_flags(args.repo))
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(render(rows))
    print(f"{len(rows)} rows, {len({r[0] for r in rows})} flags")


if __name__ == "__main__":
    main()
