"""Writes the drop-in's winmm forwarders from the export names of THIS PC's System32 winmm.dll (no Microsoft file is
copied: only the names are read). Out: <out>/winmm.def, <out>/winmm_stubs.S, <out>/winmm_names.c.
Each stub jumps through dropin_winmm_ptrs[i]; the first call of each resolves it from System32's winmm.dll
(dropin_winmm_slow -> dropin_winmm_resolve in winmm_names.c), so nothing is loaded inside DllMain.
Usage: python -I gen_winmm.py <System32 winmm.dll> <out dir>"""
import os
import struct
import sys


def export_names(path):
    d = open(path, "rb").read()
    pe = struct.unpack_from("<I", d, 0x3C)[0]
    nsec = struct.unpack_from("<H", d, pe + 6)[0]
    optsz = struct.unpack_from("<H", d, pe + 20)[0]
    opt = pe + 24
    exp_rva = struct.unpack_from("<I", d, opt + 112)[0]   # PE32+ data directory 0
    secs = []
    for i in range(nsec):
        s = opt + optsz + 40 * i
        vsz, va, rsz, rptr = struct.unpack_from("<IIII", d, s + 8)
        secs.append((va, max(vsz, rsz), rptr))

    def off(rva):
        for va, sz, rptr in secs:
            if va <= rva < va + sz:
                return rva - va + rptr
        raise ValueError(hex(rva))

    e = off(exp_rva)
    n_names = struct.unpack_from("<I", d, e + 24)[0]      # NumberOfNames
    names_rva = struct.unpack_from("<I", d, e + 32)[0]    # AddressOfNames
    out = []
    for i in range(n_names):
        r = struct.unpack_from("<I", d, off(names_rva) + 4 * i)[0]
        o = off(r)
        out.append(d[o:d.index(b"\0", o)].decode("ascii"))
    return out


def main():
    src, outdir = sys.argv[1], sys.argv[2]
    names = export_names(src)
    os.makedirs(outdir, exist_ok=True)
    with open(os.path.join(outdir, "winmm.def"), "w", newline="\n") as f:
        f.write("LIBRARY winmm.dll\nEXPORTS\n" + "".join("    %s\n" % n for n in names))
    with open(os.path.join(outdir, "winmm_names.c"), "w", newline="\n") as f:
        f.write("/* generated by hookshot/dropin/gen_winmm.py */\n#define WIN32_LEAN_AND_MEAN\n#include <windows.h>\n")
        f.write("#define N %d\nstatic const char *const names[N] = {\n" % len(names))
        f.write("".join('    "%s",\n' % n for n in names) + "};\nvoid *dropin_winmm_ptrs[N];\n")
        f.write("void *dropin_winmm_resolve(int i) {\n"
                "    static HMODULE sys;\n"
                "    if (!sys) { wchar_t p[MAX_PATH]; UINT n = GetSystemDirectoryW(p, MAX_PATH - 12);\n"
                "        if (n) { lstrcpyW(p + n, L\"\\\\winmm.dll\"); sys = LoadLibraryW(p); } }\n"
                "    void *f = sys ? (void *)GetProcAddress(sys, names[i]) : NULL;\n"
                "    if (!f) { OutputDebugStringA(\"squadala dropin: winmm export missing\"); ExitProcess(0xC0000139); }\n"
                "    dropin_winmm_ptrs[i] = f;\n    return f;\n}\n")
    with open(os.path.join(outdir, "winmm_stubs.S"), "w", newline="\n") as f:
        f.write("# generated by hookshot/dropin/gen_winmm.py\n    .text\n")
        for i, n in enumerate(names):
            f.write("    .globl %s\n%s:\n    movq dropin_winmm_ptrs+%d(%%rip), %%rax\n    testq %%rax, %%rax\n"
                    "    jz 1f\n    jmp *%%rax\n1:  movl $%d, %%eax\n    jmp dropin_winmm_slow\n" % (n, n, 8 * i, i))
        f.write("dropin_winmm_slow:\n"
                "    pushq %rcx\n    pushq %rdx\n    pushq %r8\n    pushq %r9\n    subq $0x68, %rsp\n"
                "    movdqu %xmm0, 0x20(%rsp)\n    movdqu %xmm1, 0x30(%rsp)\n    movdqu %xmm2, 0x40(%rsp)\n"
                "    movdqu %xmm3, 0x50(%rsp)\n    movl %eax, %ecx\n    call dropin_winmm_resolve\n"
                "    movdqu 0x20(%rsp), %xmm0\n    movdqu 0x30(%rsp), %xmm1\n    movdqu 0x40(%rsp), %xmm2\n"
                "    movdqu 0x50(%rsp), %xmm3\n    addq $0x68, %rsp\n"
                "    popq %r9\n    popq %r8\n    popq %rdx\n    popq %rcx\n    jmp *%rax\n")
    print("winmm forwarders: %d names" % len(names))


if __name__ == "__main__":
    main()
